CREATE TABLE cities
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name       VARCHAR(255)                            NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_cities PRIMARY KEY (id),
    CONSTRAINT uc_cities_name UNIQUE (name)
);

CREATE UNIQUE INDEX ux_cities_name_lower ON cities (LOWER(name));

INSERT INTO cities (name, created_at, updated_at)
SELECT MIN(trimmed), CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM (
    SELECT TRIM(city) AS trimmed
    FROM students
    WHERE city IS NOT NULL
      AND TRIM(city) <> ''
) names
GROUP BY LOWER(trimmed);

ALTER TABLE students
    ADD COLUMN city_id BIGINT;

ALTER TABLE students
    ADD CONSTRAINT fk_students_city FOREIGN KEY (city_id) REFERENCES cities (id) ON DELETE SET NULL;

UPDATE students s
SET city_id = c.id,
    city    = c.name
FROM cities c
WHERE s.city IS NOT NULL
  AND TRIM(s.city) <> ''
  AND LOWER(TRIM(s.city)) = LOWER(c.name);
